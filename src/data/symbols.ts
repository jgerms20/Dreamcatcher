export function findSymbols(query: string): DreamSymbol[] {
  const q = query.trim().toLowerCase()
  if (!q) return SYMBOLS
  return SYMBOLS.filter(
    (s) =>
      s.name.toLowerCase().includes(q) ||
      s.aliases.some((a) => a.toLowerCase().includes(q)) ||
      s.category.toLowerCase().includes(q) ||
      s.summary.toLowerCase().includes(q),
  )
}

export function matchSymbolsInText(text: string): DreamSymbol[] {
  const t = text.toLowerCase()
  return SYMBOLS.filter((s) => {
    // Name parts ("Waves / Ocean" → waves, ocean) plus aliases, matched on word
    // boundaries with an optional plural/singular 's' on the last word.
    const terms = [
      ...s.name.toLowerCase().split(/\s*\/\s*/),
      ...s.aliases.map((a) => a.toLowerCase()),
    ]
    return terms.some((term) => {
      const core = term.replace(/\s*\(.*\)/, '').trim()
      if (!core) return false
      const escaped = core.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/s?$/, 's?')
      return new RegExp(`\\b${escaped}\\b`, 'i').test(t)
    })
  })
}
